#!/usr/bin/env node
// Writes support/docs-pages.ts from docs/docs.json and each page's frontmatter
// and `##` headings. The list is committed rather than read at run time so the
// suite keeps its expectations after docs/ is retired; `--check` (run by
// tests/docs/inventory.e2e.ts) fails while docs/ exists and the two disagree.
// Run: `pnpm sync:docs`.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const docsRoot = path.resolve(here, '../../../docs');
const out = path.resolve(here, '../support/docs-pages.ts');

function readDocs(root = docsRoot) {
  const config = JSON.parse(readFileSync(path.join(root, 'docs.json'), 'utf8'));
  const pages = [];
  for (const tab of config.navigation.tabs) {
    // A tab lists groups, or its pages directly (Examples), which take the tab's name as their group.
    for (const group of tab.groups ?? [{ group: tab.tab, pages: tab.pages }]) {
      for (const source of group.pages) {
        if (typeof source !== 'string') throw new Error(`nested group in ${group.group} is not supported`);
        const text = readFileSync(path.join(root, `${source}.mdx`), 'utf8');
        const front = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? '';
        const field = (name) => {
          const match = new RegExp(`^"?${name}"?:\\s*(.*)$`, 'm').exec(front)?.[1]?.trim();
          return match === undefined ? undefined : match.replace(/^(["'])(.*)\1$/, '$2');
        };
        const body = text.slice(front.length + 8).replace(/^```[\s\S]*?^```/gm, '');
        const headings = [...body.matchAll(/^## (.+)$/gm)].map(([, heading]) =>
          heading
            .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
            .replace(/[`*_]/g, '')
            .replace(/\s*\{#[^}]*\}\s*$/, '')
            .trim(),
        );
        const title = field('title');
        if (title === undefined) throw new Error(`${source}.mdx has no title`);
        pages.push({
          slug: source === 'index' ? '' : source.replace(/\/index$/, ''),
          source,
          title,
          ...(field('sidebarTitle') === undefined ? {} : { sidebarTitle: field('sidebarTitle') }),
          description: field('description') ?? '',
          tab: tab.tab,
          group: group.group,
          headings,
        });
      }
    }
  }
  const redirects = config.redirects.map(({ source, destination }) => ({ source, destination }));
  return { pages, redirects };
}

function render({ pages, redirects }) {
  return `// Generated by scripts/sync-docs-pages.mjs from docs/docs.json; run \`pnpm sync:docs\` after a docs nav change.

export interface DocsPage {
  /** URL path below the docs base; \`''\` is the home page. */
  readonly slug: string;
  /** The page's file below docs/, without \`.mdx\`; differs from the slug for an \`index\` page. */
  readonly source: string;
  readonly title: string;
  readonly sidebarTitle?: string;
  readonly description: string;
  readonly tab: string;
  readonly group: string;
  /** The page's \`##\` headings, in order, as plain text. */
  readonly headings: readonly string[];
}

export const docsPages: readonly DocsPage[] = ${JSON.stringify(pages, null, 2)};

/** Old docs paths and where they now land, both relative to the docs base. */
export const docsRedirects: readonly { readonly source: string; readonly destination: string }[] = ${JSON.stringify(redirects, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const docs = readDocs();
  const text = render(docs);
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== text) {
      console.error('support/docs-pages.ts is out of date with docs/; run `pnpm sync:docs` and review the diff.');
      process.exit(1);
    }
    console.log('support/docs-pages.ts matches docs/');
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${docs.pages.length} pages and ${docs.redirects.length} redirects to ${path.relative(process.cwd(), out)}`);
  }
}
