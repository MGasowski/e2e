/**
 * A page, tab, or card icon: a Font Awesome name, or an image path
 * (`/docs/images/icons/expo.svg`) for brands. Decorative; the label beside it names the thing.
 */
export function DocsIcon({ icon, className }: { icon: string | undefined; className?: string }) {
  if (!icon) return null;
  if (icon.startsWith("/") || icon.startsWith("http")) {
    // eslint-disable-next-line @next/next/no-img-element -- small static brand marks; next/image adds nothing
    return <img src={icon} alt="" aria-hidden="true" className={cn("docs-icon-image object-contain", className)} />;
  }
  const Icon = ICONS[icon];
  return Icon ? <Icon aria-hidden="true" strokeWidth={1.6} className={className} /> : null;
}
